import { expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { notExcludedFromDeno, parseBaseline, parseJunitCounts, skipProblem } from "./gate.ts";

test("parseBaseline reads the bun_expected column per file and skips totals", () => {
  const text = [
    "file  deno_total step_parents bun_expected",
    "src/a.test.ts                  65            6           59",
    "TOTAL unit (1 files)           65            6           59",
  ].join("\n");
  expect(parseBaseline(text)).toStrictEqual(new Map([["src/a.test.ts", 59]]));
});

test("parseJunitCounts reads a real Bun report: file totals, skipped and todo tests", () => {
  // Generated by Bun 1.4.4 from a file with one passing, one skipped and one todo test, plus a
  // describe block named like the file (which must not be mistaken for the file total).
  const xml = readFileSync(new URL("./fixtures/bun-junit-sample.xml", import.meta.url), "utf8");
  expect(parseJunitCounts(xml)).toStrictEqual(
    new Map([["src/sample.test.ts", { tests: 4, skipped: 2 }]]),
  );
});

test("notExcludedFromDeno matches directory prefixes and exact files", () => {
  const excludes = ["test_support/", "src/utils/retry.test.ts"];
  expect(
    notExcludedFromDeno(
      ["test_support/assert.test.ts", "src/utils/retry.test.ts", "src/config.test.ts"],
      excludes,
    ),
  ).toStrictEqual(["src/config.test.ts"]);
});

test("skipProblem fails skips beyond the file's allowance", () => {
  expect(skipProblem("a.test.ts", 0)).toBeUndefined();
  expect(skipProblem("a.test.ts", 1)).toBe("a.test.ts: 1 skipped or todo tests (allowed: 0)");
  expect(skipProblem("b.test.ts", 1, 1)).toBeUndefined();
  expect(skipProblem("b.test.ts", 2, 1)).toBe("b.test.ts: 2 skipped or todo tests (allowed: 1)");
});
